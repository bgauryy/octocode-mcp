import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { compile } from 'json-schema-to-typescript';
import { root } from './entry-points.ts';
import { recordVariants, type RecordTypeEntry } from './runtime/record-variants.ts';
import { isReply } from './script-support.ts';

/** The generated declarations: command input, command result and record payload types, compiled from assets/catalog.json. */
export const catalogTypesFile = join(root, 'src/runtime/catalog-types.generated.ts');

const pascal = (name: string): string => name.split(/[^A-Za-z0-9]+/).filter(Boolean).map(word => word[0]!.toUpperCase() + word.slice(1)).join('');
const quote = (name: string): string => JSON.stringify(name).replaceAll('"', "'");

interface CommandEntry { readonly name: string; readonly inputSchema?: Record<string, unknown> }
interface Catalog { readonly commands: readonly CommandEntry[]; readonly recordTypes: readonly RecordTypeEntry[]; readonly results: Record<string, unknown>; readonly $defs: Record<string, unknown> }

function readCatalog(): Catalog {
  const value: unknown = JSON.parse(readFileSync(join(root, 'assets/catalog.json'), 'utf8'));
  if (!isReply(value) || !Array.isArray(value.commands) || !Array.isArray(value.recordTypes) || !isReply(value.results) || !isReply(value.$defs)) throw Error('catalog.json lacks commands, recordTypes, results or $defs');
  return { commands: value.commands, recordTypes: value.recordTypes, results: value.results, $defs: value.$defs };
}

/** TypeScript declarations for every command input and record payload of the catalog. The runtime validator stays the authority: conditional rules (`not`, `if`, `dependentRequired`, cross-field `oneOf`) are not expressible and are dropped. */
export async function renderCatalogTypes(): Promise<string> {
  const catalog = readCatalog();
  const inputs = catalog.commands.filter(command => command.inputSchema);
  const inputName = (name: string): string => pascal(name) + 'Input';
  const resultName = (name: string): string => pascal(name) + 'Result';
  const dataName = (type: string): string => pascal(type) + 'Data';
  const definitions: Record<string, unknown> = { ...catalog.$defs };
  for (const command of inputs) definitions[inputName(command.name)] = command.name === 'record' ? { ...command.inputSchema, oneOf: recordVariants(catalog.recordTypes) } : command.inputSchema;
  for (const command of catalog.commands) {
    const result = catalog.results[command.name];
    if (result === undefined) throw Error(`catalog.json has no result schema for ${command.name}`);
    definitions[resultName(command.name)] = result;
  }
  for (const item of catalog.recordTypes) definitions[dataName(item.type)] = item.dataSchema;
  // A root that references every type makes the compiler declare each one, and what it references, under its own name.
  // The root interface keeps every name, including those the compiler merged into one declaration, so the maps below read it.
  const names = Object.keys(definitions).filter(key => /^[A-Z]/.test(key));
  const schema = { $defs: definitions, type: 'object', additionalProperties: false, required: names, properties: Object.fromEntries(names.map(key => [key, { $ref: `#/$defs/${key}` }])) };
  const body = await compile(schema as never, 'CatalogTypes', {
    bannerComment: '', additionalProperties: false, declareExternallyReferenced: true, enableConstEnums: false,
    // Cardinality stays a runtime check; tuple expansion of maxItems would emit every length as its own union member.
    ignoreMinAndMaxItems: true, format: false, strictIndexSignatures: true, unreachableDefinitions: true,
  });
  const declarations = body.replace(/^export interface CatalogTypes \{/m, 'interface CatalogTypes {').trim().replace(/[ \t]+$/gm, '');
  const map = (entries: readonly (readonly [string, string])[]): string => entries.map(([key, type]) => `  ${quote(key)}: ${type};`).join('\n');
  return `// @generated by src/catalog-types.ts from assets/catalog.json (\`yarn types\`); do not edit.
/* eslint-disable */

${declarations}

/** The input of each catalog command that has an input schema, keyed by command name. */
export interface CommandInputs {
${map(inputs.map(command => [command.name, `CatalogTypes['${inputName(command.name)}']`] as const))}
}
/** The result of each catalog command as printed on the wire (null members removed), keyed by command name. */
export interface CommandResults {
${map(catalog.commands.map(command => [command.name, `CatalogTypes['${resultName(command.name)}']`] as const))}
}
/** The \`data\` payload of each record type, keyed by record type. */
export interface RecordData {
${map(catalog.recordTypes.map(item => [item.type, `CatalogTypes['${dataName(item.type)}']`] as const))}
}
export type CommandInput<N extends keyof CommandInputs> = CommandInputs[N];
export type CommandResult<N extends keyof CommandResults> = CommandResults[N];
export type RecordType = keyof RecordData;
`;
}

/** Writes the declarations; with \`check\`, fails when the committed file differs instead. */
export async function emitCatalogTypes(check = false): Promise<void> {
  const text = await renderCatalogTypes();
  if (!check) return writeFileSync(catalogTypesFile, text);
  let current = '';
  try { current = readFileSync(catalogTypesFile, 'utf8'); } catch { /* a missing file is stale */ }
  if (current !== text) throw Error('src/runtime/catalog-types.generated.ts is stale: run `yarn types` and commit the result');
}
