#!/usr/bin/env node
/**
 * Builds what Pi loads: one bundle of the compiled extension, named by its content hash, behind a CommonJS entry.
 *
 * Pi evaluates an extension's entry once per process and calls its factory again on every `/reload`; an ES module (this
 * package is `"type": "module"`) and everything it imports stay in Node's import cache, keyed by URL, so a reload kept
 * running the first build and only a restart loaded new code. The bundle holds all of this package's modules in one file
 * named by its content hash, and the entry's factory reads the current name from `pi/current` each time it runs, so a
 * reload after a build imports a URL Node has never seen.
 * Dependencies stay external (shared, unchanged across our builds). Subagents start fresh processes and keep loading
 * `dist/index.js`.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

/** The bundle name `<dir>/current` points to, or undefined before the first build. */
function readCurrent(dir) {
  try {
    return fs.readFileSync(path.join(dir, 'current'), 'utf8').trim() || undefined;
  } catch {
    return undefined;
  }
}

/** Bundles `<dist>/index.js` into `<dist>/pi/octocode-<hash>.js` (keeping the previous bundle) and writes `<dist>/pi-entry.cjs`; returns the entry path. */
export async function bundlePiEntry(dist) {
  const result = await build({
    entryPoints: [path.join(dist, 'index.js')],
    bundle: true,
    format: 'esm',
    platform: 'node',
    packages: 'external',
    write: false,
    logLevel: 'silent',
  });
  const code = result.outputFiles[0].contents;
  const name = `octocode-${crypto.createHash('sha256').update(code).digest('hex').slice(0, 16)}.js`;
  // Two folders below the package root, like every compiled module, so paths found from `import.meta.url` still hold.
  const dir = path.join(dist, 'pi');
  fs.mkdirSync(dir, { recursive: true });
  const previous = readCurrent(dir);
  fs.writeFileSync(path.join(dir, name), code);
  // The pointer to the current bundle, swapped last and atomically: a reload mid-build, or a build that dies half way,
  // still finds a complete bundle.
  const pointer = path.join(dir, 'current.tmp');
  fs.writeFileSync(pointer, name);
  fs.renameSync(pointer, path.join(dir, 'current'));
  // Only the new and the previous bundle stay: a process that read the old pointer just before the swap can still import
  // it. A rebuild with the same content keeps the bundles it found.
  if (previous !== name) {
    for (const file of fs.readdirSync(dir)) {
      if (file.startsWith('octocode-') && file.endsWith('.js') && file !== name && file !== previous) fs.rmSync(path.join(dir, file), { force: true });
    }
  }
  const entry = path.join(dist, 'pi-entry.cjs');
  fs.writeFileSync(
    entry,
    [
      '// Generated by scripts/bundle-pi.mjs. Pi evaluates this file once per process and calls its factory again on every',
      '// /reload, so the factory looks up the current bundle each time; the bundle is named by its content hash, so a rebuild',
      "// is a URL Node's module cache has never seen.",
      "const fs = require('node:fs');",
      "const path = require('node:path');",
      "const { pathToFileURL } = require('node:url');",
      'module.exports = async function octocode(pi) {',
      "  const name = fs.readFileSync(path.join(__dirname, 'pi', 'current'), 'utf8').trim();",
      "  const mod = await import(pathToFileURL(path.join(__dirname, 'pi', name)).href);",
      '  return mod.default(pi);',
      '};',
      '',
    ].join('\n'),
  );
  return entry;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await bundlePiEntry(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'dist'));
}
