#!/usr/bin/env node
// Render the Homebrew formula for the native `octocode` binary from the
// PUBLISHED npm platform packages. The tap (github.com/bgauryy/homebrew-octocode)
// receives a copy of the output; this repo is the formula's single source.
//
//   node skills-dev/octocode-dev/scripts/dev.mjs brew:formula [version] [--out FILE]
//
// Version defaults to the `latest` dist-tag of @octocodeai/octocode-native.
// Hashes are computed from the registry's bytes, never from a local `npm pack`
// (a repack is not guaranteed to be byte-identical).
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const REGISTRY = 'https://registry.npmjs.org';
const PACKAGE = '@octocodeai/octocode-native';
// Homebrew os/arch → npm platform package. Linux uses the glibc builds (glibc ≥ 2.30).
const TARGETS = {
  macos: { arm: 'darwin-arm64', intel: 'darwin-x64' },
  linux: { arm: 'linux-arm64-gnu', intel: 'linux-x64-gnu' },
};

const args = process.argv.slice(2);
const outIndex = args.indexOf('--out');
const out = path.resolve(
  outIndex >= 0 ? args[outIndex + 1] : path.join(ROOT, 'packages/octocode-native/homebrew/octocode.rb')
);
const requested = args.find((arg, index) => !arg.startsWith('--') && index !== outIndex + 1);

async function json(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.json();
}

async function sha256(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return createHash('sha256').update(Buffer.from(await response.arrayBuffer())).digest('hex');
}

const version = requested ?? (await json(`${REGISTRY}/${PACKAGE}/latest`)).version;
const blocks = {};
for (const [os, arches] of Object.entries(TARGETS)) {
  blocks[os] = {};
  for (const [arch, platform] of Object.entries(arches)) {
    const name = `${PACKAGE}-${platform}`;
    const { dist } = await json(`${REGISTRY}/${name}/${version}`);
    blocks[os][arch] = { url: dist.tarball, sha256: await sha256(dist.tarball) };
    console.log(`${platform.padEnd(16)} ${blocks[os][arch].sha256}`);
  }
}

const arch = (os, cpu) => `    on_${cpu} do
      url "${blocks[os][cpu].url}"
      sha256 "${blocks[os][cpu].sha256}"
    end`;

const formula = `# Generated by skills-dev/octocode-dev/scripts/brew-formula.mjs in github.com/bgauryy/octocode
# from the published npm packages; regenerate there instead of editing this file.
class Octocode < Formula
  desc "Code research CLI for local code, GitHub, LSP, and package registries"
  homepage "https://octocode.ai"
  license "MIT"

  # The npm URL selects livecheck's Npm strategy.
  livecheck do
    url :stable
  end

  on_macos do
${arch('macos', 'arm')}
${arch('macos', 'intel')}
  end

  on_linux do
${arch('linux', 'arm')}
${arch('linux', 'intel')}
  end

  def install
    bin.install "octocode"
  end

  test do
    assert_match "octocode #{version}", shell_output("#{bin}/octocode --version")
    (testpath/"notes.txt").write "alpha\\nneedle beta\\n"
    query = '{"path":"notes.txt","matchString":"needle b[a-z]+","regex":"rust"}'
    assert_match '"line":2,"value":"needle beta"', shell_output("#{bin}/octocode localSearch '#{query}'")
  end
end
`;

mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, formula);
console.log(`✓ ${path.relative(ROOT, out)} (octocode ${version})`);
console.log('  Next: copy it to bgauryy/homebrew-octocode Formula/octocode.rb, then brew audit + brew install there.');
